/** Mescla VOZES no ctx de cada persona (só preenche o que ainda não existe —
 *  nunca sobrescreve um campo já definido na persona). */
function mergeVozes(personas: Persona[]): Persona[] {
  return personas.map((p) => {
    const v: VozesPersona | undefined = VOZES[p.id];
    if (!v) return p;
    return { ...p, ctx: { ...v, ...p.ctx } };
  });
}

